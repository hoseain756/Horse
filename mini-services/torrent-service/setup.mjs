// Harbor Web — torrent-service first-run setup
// Asks (first run only): 1) port  2) start shortcut  3) stop&clean shortcut
// Saves engine.config.json + installs the shortcuts system-wide so the user can
// type them from any terminal. Non-interactive boots (sandbox/CI/daemons) fall
// back to silent defaults without questions.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import readline from "node:readline/promises";
import { execFileSync } from "node:child_process";
import { ENGINE_DIR, DEFAULTS, readConfig, writeConfig } from "./config.mjs";

const C = {
  bold: (s) => `\x1b[1m${s}\x1b[0m`,
  dim: (s) => `\x1b[2m${s}\x1b[0m`,
  green: (s) => `\x1b[32m${s}\x1b[0m`,
  cyan: (s) => `\x1b[36m${s}\x1b[0m`,
  yellow: (s) => `\x1b[33m${s}\x1b[0m`,
};

// Entry point used by index.mjs at boot and by `npm run setup`.
export async function ensureConfig() {
  const existing = readConfig();
  if (existing) return { cfg: existing, ranWizard: false };

  if (!process.stdin.isTTY || process.env.CI) {
    // headless boot (sandbox, docker, systemd) → silent defaults, no questions.
    // loopback host here: servers should opt into 0.0.0.0 explicitly via env.
    const cfg = { ...DEFAULTS, host: "127.0.0.1", installedAt: new Date().toISOString() };
    writeConfig(cfg);
    return { cfg, ranWizard: false };
  }

  const cfg = await askWizard();
  writeConfig(cfg);
  installShortcuts(cfg);
  return { cfg, ranWizard: true };
}

async function askWizard() {
  console.log("");
  console.log(C.bold("🐴 Horse torrent engine — الإعداد الأول (مرة واحدة فقط)"));
  console.log(C.dim("اضغط Enter مباشرة لقبول القيمة الافتراضية بين الأقواس."));
  console.log("");

  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });

  // Line queue — so users who PASTE all answers at once don't lose lines
  // (rl.question drops lines that arrive between prompts).
  const queued = [];
  let waiter = null;
  let rlClosed = false;
  rl.on("line", (line) => {
    const l = line.trim();
    if (waiter) {
      const w = waiter;
      waiter = null;
      w.resolve(l);
    } else {
      queued.push(l);
    }
  });
  rl.on("close", () => {
    rlClosed = true;
    if (waiter) {
      const w = waiter;
      waiter = null;
      w.reject(new Error("EOF"));
    }
  });

  const nextLine = () =>
    new Promise((resolve, reject) => {
      if (queued.length) return resolve(queued.shift());
      if (rlClosed) return reject(new Error("EOF"));
      waiter = { resolve, reject };
    });

  const ask = async (label, fallback, validate) => {
    for (;;) {
      process.stdout.write(` ${C.cyan(label)} ${C.dim(`(${fallback})`)}: `);
      let answer;
      try {
        answer = await nextLine();
      } catch {
        process.stdout.write("\n");
        return fallback; // stdin closed → accept default
      }
      if (!answer) {
        process.stdout.write(`${C.dim(fallback)}\n`);
        return fallback;
      }
      const err = validate ? validate(answer) : null;
      if (!err) {
        process.stdout.write("\n");
        return answer;
      }
      process.stdout.write("\n");
      console.log(`   ${C.yellow(`✗ ${err}`)}`);
    }
  };

  let port;
  let startShortcut;
  let stopShortcut;
  try {
    port = Number.parseInt(
      await ask("1) البورت", DEFAULTS.port, (v) => {
        const n = Number.parseInt(v, 10);
        if (!Number.isInteger(n) || n < 1 || n > 65535) return "أدخل رقم بورت صحيح (1-65535)";
        return null;
      }),
      10,
    );
    startShortcut = await ask("2) اختصار التشغيل", DEFAULTS.startShortcut, (v) =>
      /^[a-zA-Z0-9][a-zA-Z0-9_-]{0,31}$/.test(v) ? null : "حروف إنجليزية/أرقام/-/_ فقط",
    );
    stopShortcut = await ask("3) اختصار الإغلاق والتنظيف", DEFAULTS.stopShortcut, (v) =>
      /^[a-zA-Z0-9][a-zA-Z0-9_-]{0,31}$/.test(v)
        ? v === startShortcut
          ? "يجب أن يختلف عن اختصار التشغيل"
          : null
        : "حروف إنجليزية/أرقام/-/_ فقط",
    );
  } finally {
    rl.close();
  }

  console.log("");
  return { port, host: DEFAULTS.host, startShortcut, stopShortcut, installedAt: new Date().toISOString() };
}

// ---------------------------------------------------------------- shortcuts --
function startScriptUnix() {
  return [
    "#!/usr/bin/env bash",
    `# Generated by Horse torrent-service setup — do not edit by hand`,
    `cd "${ENGINE_DIR}" || exit 1`,
    `exec npm start`,
    "",
  ].join("\n");
}

function stopScriptUnix() {
  return [
    "#!/usr/bin/env bash",
    `# Generated by Horse torrent-service setup — do not edit by hand`,
    `cd "${ENGINE_DIR}" || exit 1`,
    `exec node stop.mjs "$@"`,
    "",
  ].join("\n");
}

function startScriptWin(name) {
  return [
    "@echo off",
    "chcp 65001 >nul",
    `rem Generated by Horse torrent-service setup — do not edit by hand`,
    `cd /d "${ENGINE_DIR}"`,
    "call npm start",
    "",
  ].join("\r\n");
}

function stopScriptWin(name) {
  return [
    "@echo off",
    "chcp 65001 >nul",
    `rem Generated by Horse torrent-service setup — do not edit by hand`,
    `cd /d "${ENGINE_DIR}"`,
    `node stop.mjs %*`,
    "",
  ].join("\r\n");
}

function installShortcuts(cfg) {
  try {
    if (process.platform === "win32") installWindows(cfg);
    else installUnix(cfg);
  } catch (e) {
    console.log(C.yellow(` ⚠ تعذّر تثبيت الاختصارات تلقائياً (${e?.message ?? e})`));
    console.log(C.dim(`   يمكنك التشغيل يدوياً دائماً من مجلد الخدمة: npm start`));
  }
}

function installUnix(cfg) {
  const binDir = path.join(os.homedir(), ".local", "bin");
  fs.mkdirSync(binDir, { recursive: true });

  const startBin = path.join(binDir, cfg.startShortcut);
  const stopBin = path.join(binDir, cfg.stopShortcut);
  fs.writeFileSync(startBin, startScriptUnix(), { mode: 0o755 });
  fs.writeFileSync(stopBin, stopScriptUnix(), { mode: 0o755 });

  // Prefer /usr/local/bin when writable (already on PATH almost everywhere).
  let globalOk = false;
  try {
    fs.accessSync("/usr/local/bin", fs.constants.W_OK | fs.constants.X_OK);
    for (const [src, dst] of [
      [startBin, path.join("/usr/local/bin", cfg.startShortcut)],
      [stopBin, path.join("/usr/local/bin", cfg.stopShortcut)],
    ]) {
      try {
        fs.unlinkSync(dst);
      } catch {}
      fs.copyFileSync(src, dst);
      fs.chmodSync(dst, 0o755);
    }
    globalOk = true;
  } catch {
    patchUnixRcPaths(); // make sure ~/.local/bin is on PATH for future shells
  }

  console.log(C.green(` ✅ اختصار التشغيل: ${cfg.startShortcut}`));
  console.log(C.green(` ✅ اختصار الإغلاق والتنظيف: ${cfg.stopShortcut}`));
  if (globalOk) {
    console.log(C.dim("    (مثبت في /usr/local/bin — يعمل من أي مجلد)"));
  } else {
    console.log(C.dim(`    (مثبت في ~/.local/bin — افتح تيرمنال جديد إذا لم يتعرف عليه)`));
  }
}

function patchUnixRcPaths() {
  const line = 'export PATH="$HOME/.local/bin:$PATH" # added by Horse torrent-service setup';
  const rcFiles = [".bashrc", ".zshrc", ".profile"].map((f) => path.join(os.homedir(), f));
  for (const rc of rcFiles) {
    try {
      if (!fs.existsSync(rc)) continue;
      const content = fs.readFileSync(rc, "utf8");
      if (content.includes(".local/bin:$PATH") || content.includes(line)) continue;
      fs.appendFileSync(rc, `\n${line}\n`);
    } catch {}
  }
}

function installWindows(cfg) {
  // .cmd shims live next to the engine; the engine folder is appended to the
  // user PATH via the registry (PowerShell — no setx 1024-char truncation).
  fs.writeFileSync(path.join(ENGINE_DIR, `${cfg.startShortcut}.cmd`), startScriptWin(cfg.startShortcut));
  fs.writeFileSync(path.join(ENGINE_DIR, `${cfg.stopShortcut}.cmd`), stopScriptWin(cfg.stopShortcut));

  const ps = (cmd) => {
    try {
      return execFileSync("powershell", ["-NoProfile", "-Command", cmd], { encoding: "utf8" }).trim();
    } catch {
      return "";
    }
  };

  const current = ps(`[Environment]::GetEnvironmentVariable('Path','User')`);
  if (current && !current.toLowerCase().split(";").includes(ENGINE_DIR.toLowerCase())) {
    ps(`[Environment]::SetEnvironmentVariable('Path', [Environment]::GetEnvironmentVariable('Path','User') + ';${ENGINE_DIR.replace(/'/g, "''")}', 'User')`);
    console.log(C.dim("    (تمت إضافة مجلد الخدمة إلى PATH للمستخدم الحالي)"));
  }

  console.log(C.green(` ✅ اختصار التشغيل: ${cfg.startShortcut}`));
  console.log(C.green(` ✅ اختصار الإغلاق والتنظيف: ${cfg.stopShortcut}`));
  console.log(C.dim("    (افتح نافذة CMD جديدة حتى يتعرف عليها)"));
}

// Allow direct use:  npm run setup
if (import.meta.url === `file://${process.argv[1]}`) {
  ensureConfig()
    .then(({ ranWizard }) => {
      if (!ranWizard) console.log("Config already exists — nothing to do.");
      process.exit(0);
    })
    .catch((e) => {
      console.error(e);
      process.exit(1);
    });
}
